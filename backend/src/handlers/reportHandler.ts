import { APIGatewayProxyEventV2, APIGatewayProxyStructuredResultV2 } from 'aws-lambda';
import { GetCommand, PutCommand, QueryCommand } from '@aws-sdk/lib-dynamodb';
import { GetObjectCommand, PutObjectCommand } from '@aws-sdk/client-s3';
import { getSignedUrl } from '@aws-sdk/s3-request-presigner';
import crypto from 'crypto';
import { ddb, ENV, s3 } from '../lib/aws';
import { assertPatientAccess, recordAuditEvent } from '../lib/caregiverAuth';
import { AppError, extractAuthPrincipal, handleError, jsonResponse, logger, parseJsonBody } from '../lib/http';
import { CreateReportSchema } from '../schemas/validation';
import { materializeTodayDosesForPatient } from './doseHandler';
import { computeAdherenceMetrics } from './analyticsHandler';
import { AdherenceReport, DoseRecord } from '../types/models';

function buildCsvReportContent(patientId: string, doses: DoseRecord[], summary: ReturnType<typeof computeAdherenceMetrics>): string {
  const header = [
    'Dose ID',
    'Patient ID',
    'Medication Name',
    'Dosage Description',
    'Scheduled Date',
    'Scheduled Time',
    'Status',
    'Confirmed At',
    'Missed At',
    'Workflow Status',
  ].join(',');

  const escapeCsv = (val: string | undefined) => {
    if (!val) return '""';
    return `"${val.replace(/"/g, '""')}"`;
  };

  const rows = doses.map((d) =>
    [
      escapeCsv(d.doseId),
      escapeCsv(d.patientId),
      escapeCsv(d.medicationName),
      escapeCsv(d.dosageDescription),
      escapeCsv(d.scheduledDate),
      escapeCsv(d.scheduledTime),
      escapeCsv(d.status),
      escapeCsv(d.confirmedAt || ''),
      escapeCsv(d.missedAt || ''),
      escapeCsv(d.workflowStatus || ''),
    ].join(',')
  );

  const metaFooter = [
    '',
    `"Summary Metrics","Total Scheduled: ${summary.totalDoses}","Taken: ${summary.takenCount}","Missed: ${summary.missedCount}","Pending: ${summary.pendingCount}","Overall Adherence: ${summary.overallAdherenceRate}%"`,
    `"Generated By","DoseGuard AI Serverless Medication Safety Platform","Generated At: ${new Date().toISOString()}"`,
  ];

  return [header, ...rows, ...metaFooter].join('\n');
}

export const handler = async (
  event: APIGatewayProxyEventV2
): Promise<APIGatewayProxyStructuredResultV2> => {
  const requestId = event.requestContext?.requestId;
  try {
    const principal = extractAuthPrincipal(event);
    const method = event.requestContext?.http?.method || 'GET';
    const rawPath = event.rawPath || '';
    const requestedPatientId = event.queryStringParameters?.patientId || principal.userId;

    // 1. POST /api/v1/reports — Generate new adherence report and upload to private S3 bucket
    if (method === 'POST' && rawPath.endsWith('/reports')) {
      const bodyInput = CreateReportSchema.parse(parseJsonBody(event.body));
      const targetPatientId = bodyInput.patientId || requestedPatientId;

      await assertPatientAccess(principal.userId, targetPatientId, 'VIEW_ONLY');

      const allDoses = await materializeTodayDosesForPatient(targetPatientId);
      const now = new Date();
      const startCutoff = new Date(now.getTime() - bodyInput.days * 86400 * 1000)
        .toISOString()
        .slice(0, 10);
      const endCutoff = now.toISOString().slice(0, 10);

      const periodDoses = allDoses
        .filter((d) => d.scheduledDate >= startCutoff)
        .sort((a, b) =>
          `${b.scheduledDate}T${b.scheduledTime}`.localeCompare(`${a.scheduledDate}T${a.scheduledTime}`)
        );

      const metrics = computeAdherenceMetrics(periodDoses);
      const reportId = `rep_${crypto.randomUUID().slice(0, 12)}`;
      const ext = bodyInput.format === 'CSV' ? 'csv' : 'json';
      const s3Key = `reports/${targetPatientId}/${reportId}.${ext}`;

      const fileBody =
        bodyInput.format === 'CSV'
          ? buildCsvReportContent(targetPatientId, periodDoses, metrics)
          : JSON.stringify(
              {
                reportId,
                patientId: targetPatientId,
                generatedAt: now.toISOString(),
                periodStart: startCutoff,
                periodEnd: endCutoff,
                summary: {
                  totalScheduled: metrics.totalDoses,
                  totalTaken: metrics.takenCount,
                  totalMissed: metrics.missedCount,
                  totalPending: metrics.pendingCount,
                  adherencePercentage: metrics.overallAdherenceRate,
                },
                doses: periodDoses,
              },
              null,
              2
            );

      await s3.send(
        new PutObjectCommand({
          Bucket: ENV.REPORTS_BUCKET,
          Key: s3Key,
          Body: fileBody,
          ContentType: bodyInput.format === 'CSV' ? 'text/csv' : 'application/json',
          ServerSideEncryption: 'AES256',
        })
      );

      const reportRecord: AdherenceReport = {
        reportId,
        patientId: targetPatientId,
        requestedByUserId: principal.userId,
        periodStart: startCutoff,
        periodEnd: endCutoff,
        totalScheduled: metrics.totalDoses,
        totalTaken: metrics.takenCount,
        totalMissed: metrics.missedCount,
        totalPending: metrics.pendingCount,
        adherencePercentage: metrics.overallAdherenceRate,
        s3Bucket: ENV.REPORTS_BUCKET,
        s3Key,
        format: bodyInput.format,
        createdAt: now.toISOString(),
        ttl: Math.floor(now.getTime() / 1000) + 30 * 86400,
      };

      await ddb.send(
        new PutCommand({
          TableName: ENV.REPORTS_TABLE,
          Item: reportRecord,
        })
      );

      await recordAuditEvent({
        actorUserId: principal.userId,
        patientId: targetPatientId,
        action: 'ADHERENCE_REPORT_GENERATED',
        resourceId: reportId,
        metadata: { format: bodyInput.format, s3Key },
      });

      logger('INFO', 'ADHERENCE_REPORT_GENERATED', {
        patientId: targetPatientId,
        reportId,
        format: bodyInput.format,
      });

      return jsonResponse(201, { report: reportRecord });
    }

    // 2. GET /api/v1/reports — List reports for patient
    if (method === 'GET' && rawPath.endsWith('/reports')) {
      await assertPatientAccess(principal.userId, requestedPatientId, 'VIEW_ONLY');

      const res = await ddb.send(
        new QueryCommand({
          TableName: ENV.REPORTS_TABLE,
          KeyConditionExpression: 'patientId = :pid',
          ExpressionAttributeValues: {
            ':pid': requestedPatientId,
          },
          Limit: 50,
        })
      );

      const reports = ((res.Items || []) as AdherenceReport[]).sort((a, b) =>
        b.createdAt.localeCompare(a.createdAt)
      );

      return jsonResponse(200, {
        reports,
        patientId: requestedPatientId,
      });
    }

    // 3. GET /api/v1/reports/{id}/download — Generate short-lived S3 presigned URL
    if (method === 'GET' && rawPath.endsWith('/download')) {
      const reportId = decodeURIComponent(event.pathParameters?.id || '');
      if (!reportId) {
        throw new AppError(400, 'MISSING_REPORT_ID', 'Report ID is required.');
      }

      await assertPatientAccess(principal.userId, requestedPatientId, 'VIEW_ONLY');

      const reportRes = await ddb.send(
        new GetCommand({
          TableName: ENV.REPORTS_TABLE,
          Key: {
            patientId: requestedPatientId,
            reportId,
          },
        })
      );

      if (!reportRes.Item) {
        throw new AppError(404, 'REPORT_NOT_FOUND', 'Adherence report not found.');
      }

      const report = reportRes.Item as AdherenceReport;
      // Enforce strict ownership verification against the stored report's patientId
      await assertPatientAccess(principal.userId, report.patientId, 'VIEW_ONLY');

      const expiresInSeconds = 300; // 5-minute short-lived presigned URL
      const ext = report.format === 'CSV' ? 'csv' : 'json';
      const downloadUrl = await getSignedUrl(
        s3,
        new GetObjectCommand({
          Bucket: report.s3Bucket,
          Key: report.s3Key,
          ResponseContentDisposition: `attachment; filename="doseguard-report-${report.reportId}.${ext}"`,
        }),
        { expiresIn: expiresInSeconds }
      );

      await recordAuditEvent({
        actorUserId: principal.userId,
        patientId: report.patientId,
        action: 'ADHERENCE_REPORT_DOWNLOAD_URL_ISSUED',
        resourceId: report.reportId,
      });

      return jsonResponse(200, {
        reportId: report.reportId,
        downloadUrl,
        expiresInSeconds,
        format: report.format,
      });
    }

    return jsonResponse(405, {
      error: { code: 'METHOD_NOT_ALLOWED', message: `Unsupported route ${method} ${rawPath}` },
    });
  } catch (err) {
    return handleError(err, requestId);
  }
};

